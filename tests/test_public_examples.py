def test_trace_intelligence_eval_example_scorecard_matches_packet():
    scorecard = read_json(EXAMPLES / "trace-intelligence" / "eval" / "scorecard.json")
    rows = [
        json.loads(line)
        for line in read_text(EXAMPLES / "trace-intelligence" / "eval" / "run-intelligence-eval.jsonl").splitlines()
        if line.strip()
    ]
    readme = read_text(EXAMPLES / "trace-intelligence" / "eval" / "README.md")

    assert scorecard["dataset_rows"] == len(rows)
    assert scorecard["context_waste"]["f1"] == 1.0
    assert scorecard["run_intel"]["f1"] == 0.933
    assert scorecard["run_intel"]["fn"] == 1
    assert "adv-recover-novocab" in readme
    assert "opentraces trace get <trace-id> --waste --json" in readme
    assert "opentraces trace compare <trace-a> <trace-b> --json" in readme
