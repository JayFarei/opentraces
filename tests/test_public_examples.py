from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"

PUBLIC_EXAMPLES = {
    "standup": "turn sanitized bucket-session summaries into a narrative",
    "trace-capsule": "bounded, redacted trace episode",
    "intent-pr": "ties branch commits back to originating sessions",
    "spotlight": "bounded trace-search packet",
    "skill-evaluation": "synthetic verifier-candidate packet",
    "trace-intelligence/eval": "synthetic labeled evaluation packet",
}


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def read_json(path: Path) -> dict:
    return json.loads(read_text(path))


def normalized(text: str) -> str:
    return " ".join(text.split())


def test_examples_index_lists_each_public_example():
    index = read_text(EXAMPLES / "README.md")
    flat_index = normalized(index)

    assert "`examples/` is the only public examples/demo folder" in index
    for example, purpose in PUBLIC_EXAMPLES.items():
        assert f"`{example}/`" in index
        assert purpose in flat_index


def test_each_public_example_has_task_contract():
    private_markers = [
        "/" + "Users/",
        "OPENAI" + "_API_KEY",
        "ANTHROPIC" + "_API_KEY",
        "GITHUB" + "_TO" + "KEN",
        "ghp_",
        "hf_",
        "sk-",
    ]

    for example in PUBLIC_EXAMPLES:
        readme = read_text(EXAMPLES / example / "README.md")

        assert "## Task" in readme, example
        assert "## Inputs" in readme, example
        assert ("## Run" in readme or "## Expected Output" in readme), example
        for marker in private_markers:
            assert marker not in readme, f"{example} contains private marker {marker}"


def test_public_examples_do_not_use_stale_cli_forms():
    combined = "\n".join(
        path.read_text(encoding="utf-8")
        for path in sorted(EXAMPLES.rglob("*"))
        if path.is_file()
    )

    stale_forms = [
        "--ski" + "ll review",
        "--" + "pr 123",
        "--re" + "po owner/project",
        "workflow create --temp" + "late",
        "runs/standup" + "-demo",
        "examples/skill" + "-intelligence",
        "de" + "mos/",
    ]
    for form in stale_forms:
        assert form not in combined


def test_trace_capsule_example_is_capsule_task():
    readme = read_text(EXAMPLES / "trace-capsule" / "README.md")
    capsule_path = EXAMPLES / "trace-capsule" / "capsule.sample.json"
    capsule = read_json(capsule_path)

    assert capsule["schema_version"] == "opentraces.capsule.v1"
    assert capsule["content_is_untrusted"] is True
    assert capsule["source"]["trace_id"] == "trace-example-capsule"
    assert capsule["summary"]["is_failure"] is True
    assert capsule["privacy_scope"]["system_prompt_included"] is False
    assert capsule["privacy_scope"]["reasoning_included"] is False
    assert capsule["test"]["expected"]["kind"] == "error_string"
    assert capsule["redaction"]["manifest"]["floor_satisfied"] is True
    assert capsule["redaction"]["manifest"]["floor"] == ["regex", "entropy", "business_logic"]
    assert "pytest tests/test_duration_parser.py::test_accepts_iso_duration" in capsule["test"]["command"]
    assert "opentraces capsule preview" in readme
    assert "opentraces capsule get" in readme
    assert "--issue-repo owner/project" in readme
    assert "--json > capsule.json" in readme
    assert "GitHub issue" in readme

    proc = subprocess.run(
        [
            sys.executable,
            "-c",
            "from opentraces.cli import main; main()",
            "capsule",
            "open",
            str(capsule_path),
            "--json",
        ],
        cwd=ROOT,
        text=True,
        capture_output=True,
        timeout=10,
    )
    assert proc.returncode == 0, proc.stderr
    opened = json.loads(proc.stdout)
    assert opened["capsule_id"] == capsule["capsule_id"]


